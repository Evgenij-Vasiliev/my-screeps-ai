/**
 * FACTORY MANAGER
 * Прямой вызов производства структуры Factory — сжатие энергии в батареи.
 * Не является задачей Worker'а (аналогично powerSpawn.manager.js).
 *
 * ── ГРАНИЦА ОТВЕТСТВЕННОСТИ (правка 05.10.2026 по указанию владельца) ────
 * «Фабрика работает в штатном режиме: получила 600 энергии — произвела
 * 50 батареек, и всё. Она ничего не знает ни о хранилище, ни о терминале.
 * Всё решается в системе задач для воркера».
 *
 * Поэтому здесь НЕТ ни интервала производства, ни проверок роста империи,
 * ни порогов свободных средств склада — всё это тут стояло и мешало:
 *   - порог свободных средств был недостижим (свободные не превышают
 *     FLEX_STORAGE), фабрика молчала при полной энергии;
 *   - проверка роста империи (rate) останавливала производство, когда запас
 *     падал по причинам, к фабрике не относящимся: живой замер tick 83463290
 *     дал rate = -68.295, и фабрика встала с 7 795 энергии и cd0.
 *
 * Расход регулирует СИСТЕМА ЗАДАЧ, а не сама структура:
 *   - пришла энергия от задачи — фабрика производит (движок сам проверит
 *     компоненты: 600 энергии на 50 батарей, COMMODITIES, engine
 *     factories/produce.js);
 *   - задача fillFactoryEnergy ставится, только когда энергия комнаты
 *     РАСТЁТ (сальдо склада и терминала положительное — econ.roomGrowth);
 *   - есть батареи — генератор collectFactoryBattery ставит задачу забрать.
 * Ограничений «по количеству батарей» здесь нет: батареи — кладовая империи
 * и статья дохода на рынке (ENABLE_BATTERY в market.manager.js).
 */
function run(roomState) {
  const { factory } = roomState;

  if (!factory) return;

  if (factory.cooldown > 0) return;

  if (factory.store[RESOURCE_ENERGY] > 0) {
    factory.produce(RESOURCE_BATTERY);
  }
}

module.exports = { run };
