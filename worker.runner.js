/**
 * ============================================================================
 * WORKER.RUNNER — решение о задаче для роли `worker`
 * ============================================================================
 *
 * Модуль отвечает РОВНО на один вопрос: какую задачу воркер исполняет в этом
 * тике. Работу выполняет исполнитель (`taskExecutors.executors[type]`):
 * движение, интенты и фазы (`memory.working`) — его ответственность.
 *
 * ── Откуда берётся CPU роли и сколько из него здесь ────────────────────────
 *
 * Замер на shard3 03-04.10.2026 (scripts/cpu.roles.measure.js, 9 окон):
 * подсистема `worker` = 0.883 CPU/тик на 5 воркеров при 4.6 CPU/тик империи,
 * то есть 0.18 CPU на воркера — ровно столько же, сколько на майнера.
 *
 * Модуль НЕ является источником этого расхода, и это проверено, а не
 * предположено:
 *   * задач во всех очередях империи — 34, размер секции `rooms` — 10.5 КБ
 *     (замер: node /tmp/queue.measure.js shard3);
 *   * парс + сериализация ВСЕЙ Memory — 0.13 CPU/тик на империю;
 *   * обход всех очередей (аналог countQueue по всем парам комната/тип) —
 *     0.0038 CPU;
 *   * `creep.moveTo` при живом кэше пути — 0.008-0.012 CPU (docs/move-cost-measure.json);
 *     19 из 21 крипа имеют живой кэш `_move`, медиана возраста 50 тиков.
 *
 * Остаток расхода роли — это движение и интенты исполнителей, то есть
 * полезная работа, а не накладные расходы выбора задачи.
 *
 * ── Что модуль делает, чтобы не тратить лишнего ────────────────────────────
 *
 *  1. ПОИСК ЗАДАЧИ ПО taskId ИДЁТ ДО ЧТЕНИЯ СТОРА. Стор нужен только для
 *     расчёта дальности и для исполнителя; если задача уже известна, читать
 *     `creep.store` на каждом тике незачем.
 *  2. НЕРАБОЧАЯ КОМНАТА ЗАКРЫВАЕТСЯ НА ТИК ЦЕЛИКОМ. Если в комнате нет
 *     свободных задач, это выясняется один раз (`index.work === 0`) и все
 *     простаивающие воркеры комнаты выходят, не трогая ни Memory, ни стор.
 *  3. ДАЛЬНОСТЬ СЧИТАЕТСЯ ОДИН РАЗ НА ПАРУ (КРИП, ТОЧКА МАРШРУТА) за тик.
 *     Кэш — `makeRanger`; повторный проход по той же очереди не стоит ничего.
 *  4. ОБХОД ОЧЕРЕДЕЙ ПО КРУГУ ОТ СВОЕЙ ОЧЕРЕДИ, без повторного прохода:
 *     выбранная очередь не обходится второй раз, потому что индекс уже хранит
 *     её дальность и лучшего кандидата (замер в тесте: 3 обращения к
 *     `getRangeTo` вместо 6).
 *  5. В MEMORY ПИШЕТСЯ ТОЛЬКО ПРИ СМЕНЕ ЗНАЧЕНИЯ (правило §11.1-7).
 *     Нет свободных задач — не пишется ничего вообще.
 *
 * ── Куда уходит время: бортовой замер ─────────────────────────────────────
 *
 * Модуль сам сообщает, что делает и сколько это стоит. Раз в
 * `SAMPLE_EVERY` тиков он берёт `Game.cpu.getUsed()` до и после двух своих
 * участков и накапливает результат в heap (`global.__workerDiag`). Цена самого
 * замера: один сэмплированный тик из 50, то есть ≈0.0003 CPU/тик на воркера —
 * шум по сравнению с 0.18.
 *
 * Читать с шарда:
 *
 *   JSON.stringify(global.__workerDiag, null, 1)
 *
 * Поля (CPU — среднее на вызов, за накопленное окно):
 *   ticks        — тиков наблюдения;
 *   calls        — решений принято (исполнение до вызова исполнителя);
 *   noTask       — решений, где задача не потребовалась (выход до исполнителя);
 *   scans        — построений индекса комнаты (дорогая ветка);
 *   dryExits     — выходов «в комнате свободных задач нет» (O(1));
 *   selected     — задач взято и зарезервировано;
 *   switched     — смен типа задачи (брошенный кэш пути; наблюдаемость);
 *   done/skip    — завершений задач исполнителем;
 *   cpuTask      — CPU на поиск и резерв задачи;
 *   cpuExec      — CPU на исполнителя (движение и интенты ЦЕЛИКОМ здесь);
 *   cpuSample    — сколько вызовов попало в выборку CPU.
 *
 * Сопоставление: `Memory.cpuStats.subsystems.worker` даёт полную цену роли,
 * `cpuTask` + `cpuExec` показывают, как она делится между решением и работой.
 *
 * Откат разбиения 04.10.2026: git checkout -- worker.runner.js task/runner.js
 *   task/runner.pick.js task/runner.state.js task/runner.diag.js
 * ============================================================================
 */

