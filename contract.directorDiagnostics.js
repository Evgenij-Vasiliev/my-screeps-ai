/**
 * contract.directorDiagnostics.js
 *
 * Единый диагностический контракт Director Layer.
 * Источник: ARCHITECTURE_CONTRACT V3.4, Закон №6 "Диагностика обязательна".
 *
 * НАЗНАЧЕНИЕ:
 *   Определяет обязательную структуру диагностического отчёта любого Director.
 *   Все будущие Director-модули обязаны публиковать диагностику в этом формате.
 *
 * ПРАВИЛА:
 *   - Декларативный контракт. Никакой игровой логики.
 *   - Не использует Memory.
 *   - Не выполняет проверок.
 *   - Описывает исключительно нормативную структуру отчёта.
 *
 * ИСПОЛЬЗОВАНИЕ (в будущих Director-модулях):
 *   const directorDiagnostics = require('contract.directorDiagnostics');
 *
 *   // Создать пустой отчёт в правильном формате:
 *   const report = directorDiagnostics.createReport();
 *
 *   // Проверить допустимость состояния:
 *   const valid = directorDiagnostics.STATES.includes('HEALTHY'); // => true
 *
 *   // Итоговый формат отчёта:
 *   // { state: 'HEALTHY', warnings: [], problems: [], recommendations: [] }
 */

"use strict";

// =============================================================================
// ДОПУСТИМЫЕ СОСТОЯНИЯ
// =============================================================================

/**
 * STATES
 *
 * Полный список допустимых значений поля state.
 * Director обязан использовать только эти значения.
 */
const STATES = ["HEALTHY", "WARNING", "ERROR"];

// =============================================================================
// НОРМАТИВНАЯ СТРУКТУРА ОТЧЁТА
// =============================================================================

/**
 * REPORT_SCHEMA
 *
 * Описание обязательных полей диагностического отчёта.
 * Является нормативным описанием, не валидатором.
 *
 * Каждое поле содержит:
 *   type        — тип значения
 *   description — назначение поля
 *   required    — обязательность поля
 */
const REPORT_SCHEMA = {
  /**
   * state
   * Текущее состояние директора.
   * Обязательное поле. Одно из: HEALTHY, WARNING, ERROR.
   *
   * Правила формирования (единые для всех Director):
   *   problems.length > 0              → ERROR
   *   warnings.length > 0, нет ошибок → WARNING
   *   нет ни ошибок, ни предупреждений → HEALTHY
   */
  state: {
    type: "string",
    allowedValues: STATES,
    description:
      "Текущее состояние директора. Одно из: HEALTHY, WARNING, ERROR.",
    required: true,
  },

  /**
   * warnings
   * Массив предупреждений.
   * Обязательное поле. Пустой массив если предупреждений нет.
   * Предупреждение — не критическая проблема, но требует внимания.
   */
  warnings: {
    type: "string[]",
    description:
      "Массив строк с предупреждениями. Пустой массив если предупреждений нет.",
    required: true,
  },

  /**
   * problems
   * Массив ошибок.
   * Обязательное поле. Пустой массив если ошибок нет.
   * Ошибка — критическая проблема, требующая немедленного внимания.
   */
  problems: {
    type: "string[]",
    description:
      "Массив строк с описанием ошибок. Пустой массив если ошибок нет.",
    required: true,
  },

  /**
   * recommendations
   * Массив рекомендаций по устранению проблем.
   * Обязательное поле. Пустой массив если рекомендаций нет.
   * Рекомендация — конкретное действие для устранения warning или problem.
   */
  recommendations: {
    type: "string[]",
    description:
      "Массив строк с рекомендациями по устранению. Пустой массив если рекомендаций нет.",
    required: true,
  },
};

// =============================================================================
// ФАБРИЧНАЯ ФУНКЦИЯ
// =============================================================================

/**
 * createReport(state, warnings, problems, recommendations)
 *
 * Создаёт диагностический отчёт в нормативном формате.
 * Вспомогательная функция для использования в Director-модулях.
 *
 * Если аргументы не переданы — возвращает пустой отчёт со состоянием HEALTHY.
 *
 * @param {string}   [state='HEALTHY']  — состояние директора
 * @param {string[]} [warnings=[]]      — массив предупреждений
 * @param {string[]} [problems=[]]      — массив ошибок
 * @param {string[]} [recommendations=[]] — массив рекомендаций
 * @returns {{ state: string, warnings: string[], problems: string[], recommendations: string[] }}
 */
function createReport(state, warnings, problems, recommendations) {
  return {
    state: state || "HEALTHY",
    warnings: warnings || [],
    problems: problems || [],
    recommendations: recommendations || [],
  };
}

// =============================================================================
// ЭКСПОРТ
// =============================================================================

module.exports = {
  /** Допустимые значения поля state */
  STATES,

  /** Нормативное описание структуры отчёта */
  REPORT_SCHEMA,

  /**
   * createReport() — создаёт пустой или заполненный отчёт в нормативном формате.
   * Использование: const report = directorDiagnostics.createReport();
   */
  createReport,
};
