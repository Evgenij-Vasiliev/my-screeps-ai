// ── CPU ──────────────────────────────────────────────────────────────────
// Настройки мониторинга CPU (cpuMonitor.js): как часто отчитываться,
// на каком окне усреднять, при каком уровне bucket считать критичным.
const CPU = {
  REPORT_INTERVAL: 10,
  AVERAGE_WINDOW: 100,
  BUCKET_CRITICAL: 500,

  // ── Профилирование Room Manager (ТЗ №0, временный блок) ────────────────
  // PROFILE_ENABLED: false — полностью выключает измерительный слой
  // (замеры не копятся, Memory.cpuStats.profile не обновляется, а trackRole
  // вообще не вызывает Game.cpu.getUsed).
  // PROFILE_REPORT_INTERVAL: раз в сколько тиков накопленное окно замеров
  // сбрасывается в Memory.cpuStats.profile и печатается сводка в консоль.
  // Сами замеры копятся в heap (без обращений к Memory), так что
  // сбор не создаёт заметной нагрузки; Memory пишется 1 раз в N тиков.
  // PROFILE_MAX_SAMPLES: сколько замеров (тиков) живёт в
  // Memory.cpuStats.profile до автоматического сброса. Раньше профиль
  // накапливался бессрочно: суммы/счётчики росли всю жизнь шарда, а ключи
  // комнат/блоков, встреченных когда-либо, не удалялись. Теперь это
  // ограниченное скользящее окно, сброс автоматический.
  // SAMPLE_INTERVAL: замер ролей и подсистем идёт не каждый тик, а один тик из
  // стольких (на остальных trackRole не трогает Game.cpu.getUsed вовсе).
  // Замер на живом shard3 (tests/live.cpu.instrument.js): ~80 вызовов trackRole
  // за тик, каждый — пара Game.cpu.getUsed() по ~0.2 мкс, то есть ~0.032 CPU/тик
  // постоянного налога. Интервал 7 взаимно прост со всеми TASK_GEN_INTERVAL
  // (1/2/3/5) и с интервалами отчётов (10/100), поэтому периодические блоки
  // попадают в выборку равномерно, а средние в профиле остаются несмещёнными.
  PROFILE_ENABLED: true,
  PROFILE_REPORT_INTERVAL: 100,
  PROFILE_MAX_SAMPLES: 2000,
  SAMPLE_INTERVAL: 7,

  // ── Мониторинг РОЛЕЙ (opt-in; аудит п. 9, дорожная карта задача 6) ──────
  // Ролевые бакеты — единственный замер, который висит на КАЖДОМ крипе, а не
  // на подсистеме: третий аргумент trackRole доказывает, что имя бакета — роль,
  // и тогда сэмплирование пропускает его целиком, без вызова callback.
  //
  // ROLE_ENABLED: значение ПО УМОЛЧАНИЮ для `Memory.cpuMonitorRoles`. Сам
  // переключатель живёт в Memory (его видно из консоли игры и он переживает
  // global reset):
  //   Memory.cpuMonitorRoles = true   — включить замер и отчёт по ролям
  //   Memory.cpuMonitorRoles = false  — выключить (значение по умолчанию)
  // false — роли не замеряются (Game.cpu.getUsed не вызывается ни разу за тик)
  // и не печатаются; подсистемы (roomManager/roomState/taskManager/towers/…)
  // замеряются как раньше. Разбор по ролям нужен не постоянно, а когда ищешь
  // конкретную просадку.
  ROLE_ENABLED: false,
  // ROLE_REPORT_INTERVAL: раз в сколько тиков накопленное окно ролей
  // переносится в Memory.cpuStats.roles и печатается ОДНОЙ строкой в консоль.
  // Раньше роли шли одной строкой в сводке профиля раз в 100 тиков; теперь это
  // отдельный отчёт (50 — низ аудиторского диапазона «раз в 50–100 тиков»).
  ROLE_REPORT_INTERVAL: 50,
  // ROLE_MAX_SAMPLES: сколько замерных тиков живёт Memory.cpuStats.roles до
  // автоматического сброса (как PROFILE_MAX_SAMPLES, но своё окно — ролевой
  // отчёт сбрасывается в Memory в 2 раза чаще, значит и подрезать его надо
  // раньше, чтобы размер записи не рос).
  ROLE_MAX_SAMPLES: 1000,
};

