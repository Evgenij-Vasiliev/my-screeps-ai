/**
 * ЕДИНАЯ ПОЛИТИКА ПЕРЕИСПОЛЬЗОВАНИЯ ПУТИ (reusePath) — Шаг 4 плана.
 *
 * Было: 32 вызова `moveTo` со значениями 5 / 10 / 15 / 20 / 50 без правила,
 * какое где. Теперь правило одно — по стабильности цели:
 *
 *   STABLE   — цель не меняется никогда или меняется раз в десятки-сотни
 *              тиков: storage, terminal, source/spot майнера, линк у storage.
 *              Путь переиспользуется дольше всего.
 *   NORMAL   — цель живёт десятки-сотни тиков: спавны/extension, башни,
 *              фабрика, терминал, стройплощадка, минерал, controller.
 *   VOLATILE — цель меняется каждые несколько тиков: повреждённая структура
 *              ремонта, цель апгрейда, любая цель, выбранная заново из списка.
 *              Путь пересчитывается часто, потому что ехать всё равно в новое
 *              место.
 *   OFF      — переиспользование выключено (`reusePath: 0`): нужно, когда крип
 *              застрял (например, на пути появилась постройка) и кэш надо сбросить.
 *
 * `reusePath` — это TTL кэша направлений в `creep.memory._move`
 * (docs: «The reusePath value defines the amount of ticks which the path should
 * be reused for. The default value is 5»). Больше значение — меньше пересчётов
 * пути (дешевле по CPU), но дольше живёт устаревший маршрут.
 *
 * Замер (shard3, docs/pathfinding-measure.json, docs/path-quality-measure.json):
 * один пересчёт пути на 42 тайла стоит 0.33-0.75 CPU, путь с матрицей дорог —
 * 0.10-0.19, но +30 % усталости крипа (короткий маршрут идёт через свампы).
 * Поэтому политика снижает ЧАСТОТУ пересчётов, а не цену одного поиска.
 *
 * Откат шага 4: вернуть числа из git (`git checkout -- constants.js` и файлы ролей).
 */
