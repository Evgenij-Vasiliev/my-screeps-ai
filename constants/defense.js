/**
 * Пороги ремонта дорог — ОДНИ на воркера и башню.
 *
 * Зачем в одном месте: у двух исполнителей одной цели не должно быть разных
 * порогов. Воркер закрывает дорогу на `ROAD_DONE_HITS`, а башня выбирает цель
 * по ДОЛЕ потерянных хитов (room/repair.js:248-329) и, не зная этой линии,
 * гонит ту же дорогу до максимума: болотную (25 000 хитов) — это 29 действий
 * по 10 энергии, скальную (750 000) — 937 действий.
 *
 *   ROAD_TASK_HITS — ниже этого числа генератор ставит задачу воркеру
 *                    (task/gen.repair.js, isBelowRoadThreshold);
 *   ROAD_DONE_HITS — на нём воркер закрывает задачу (task/exec.repair.js,
 *                    isDoneRepair) И башня перестаёт брать дорогу целью
 *                    (room/repair.js, pickRepairTarget).
 *
 * Полоса [2 000; 3 000] одинакова для всех дорог: у них три разных максимума
 * (5 000 равнина, 25 000 болото, 750 000 природная скала — замер 671/87/2
 * дороги, docs/REPAIR-PLAN.md:107), и абсолютные хиты — единственная шкала,
 * которая не превращает болотную дорогу в 130 тиков работы воркера, а скальную
 * в 4 480. Дороге «здоровье» не нужно: она работает при любых хитах выше нуля,
 * а исчезнувшую восстановить нечем — `createConstructionSite` в боте не
 * вызывается вовсе.
 *
 * Не-дороги (spawn, extension, башни, валы, storage, terminal) у обоих
 * исполнителей идут до максимума хитов — здесь цели и так совпадают.
 */
