// ===================================================
// ── TOWER ────────────────────────────────────────────────────────────────
// Пороги и интервалы поведения башен (ремонт стен, атака, подпитка).
const TOWER = {
  REPAIR_ENERGY_MIN: 700, // минимум энергии в башне, чтобы начать ремонт
  REPAIR_INTERVAL: 15, // период ремонта СТЕН/валов (структуры/дороги — каждый тик)
  // Бюджет ремонта структур/дорог на комнату за тик (в действиях башен).
  //
  // Зачем ограничение. После правки ремонта (цели пересобираются каждый тик,
  // у каждой башни своя цель) комната могла бы тратить до `число башен × 10`
  // энергии за тик, пока есть долг. Это не про хиты, а про ЛОГИСТИКУ: каждая
  // потраченная десятка — это задача fillTowers, которую воркер берёт с
  // приоритетом 3 и ПРЕРЫВАЕТ свою текущую задачу (worker.runner.shouldPreempt),
  // а смена цели у воркера — это Traveler с полным PathFinder.search. Именно
  // так ремонт превращается в рост CPU и в болтанку воркеров.
  //
  // 2 действия за тик = 1600 хитов ремонта в тик (при 4 башнях) и 20 энергии в
  // тик максимум на комнату. Износ дорог от шагов крипов — единицы-десятки
  // хитов в тик, то есть запас 30-100×, а подпитка башен нужна не чаще, чем раз
  // в ~25 тиков на башню (250-300 энергии буфера выше порога подпитки).
  REPAIR_ACTIONS_PER_TICK: 2,
  // Период скана стен/валов. Сознательно совпадает с REPAIR_INTERVAL: в этот
  // же тик башни ремонтируют стены, поэтому цель (самая слабая стена) считается
  // ровно тогда, когда нужна. Между сканами тяжёлая работа (разыменование стен
  // по id + проход по ним) не выполняется вообще.
  WALL_SCAN_INTERVAL: 15,
  WALL_THRESHOLD_DEFAULT: 1000, // стартовый порог прочности стен для ремонта
  WALL_THRESHOLD_STEP: 1000, // на сколько поднимаем порог с каждым уровнем
  HITS_DROP_THRESHOLD: 1500, // падение суммарных хитов стен за 1 тик = атака
  SUPPLY_THRESHOLD: 750, // ниже этого — башне нужна подпитка энергией
  // Интервала скана врагов здесь нет намеренно: комнаты с башнями ищут
  // FIND_HOSTILE_CREEPS каждый тик (room.manager.runTowerLogic) — иначе
  // башни запаздывают с реакцией на нападение и не лечат своих. Просадка
  // хитов стен (HITS_DROP_THRESHOLD) — только дополнительный сигнал тревоги,
  // поэтому проверяется раз в WALL_SCAN_INTERVAL тиков.
};

