// ===================================================
// CONSTANTS/POWERSPAWN.JS — POWER_SPAWN — пороги PowerSpawn
// ===================================================
// Реакции GPL, резервы энергии склада/терминала под processPower().
// Выделено из constants.js; потребители берут значения через barrel
// constants.js, чтобы объекты конфига оставались одним экземпляром.
// ===================================================
const { STORAGE } = require("./logistics");

// ── POWER_SPAWN ──────────────────────────────────────────────────────────
// PowerSpawn уровня RCL8 (Game.gpl — «глобальный уровень силы»).
//
// МЕХАНИКА ДВИЖКА (screeps/engine, StructurePowerSpawn.processPower):
//   потребляет 1 power + POWER_SPAWN_ENERGY_RATIO (50) энергии
//   → +1 единица прогресса GPL;
//   cooldown после вызова — 50 тиков (POWER_SPAWN_COOLDOWN);
//   store: 5000 энергии (POWER_SPAWN_ENERGY_CAPACITY) и 100 power
//   (POWER_SPAWN_POWER_CAPACITY).
// Значит минимумы ниже обязаны быть МЕНЬШЕ расхода одного вызова, иначе
// processPower() физически не запустится: движок вернёт
// ERR_NOT_ENOUGH_RESOURCES и всё.
const POWER_SPAWN = {
  // Порог «в PowerSpawn есть сырьё на обработку». Значения намеренно выше
  // расхода одного processPower() (1 power, 50 энергии): снабжение доводит
  // store до этих величин, поэтому обработка не «спотыкается» на пустом store
  // между двумя рейсами воркера.
  POWER_MIN: 10, // минимум POWER в PowerSpawn для обработки
  ENERGY_MIN: 500, // минимум энергии в PowerSpawn для обработки

  // Сколько единиц ресурса забирает ОДИН processPower() — по механике движка.
  // Держим здесь как единую точку правды: тесты и документация опираются на
  // это число, а не на «магические» 50 в коде.
  POWER_PER_PROCESS: 1,
  ENERGY_PER_PROCESS: 50,

  // ЦЕЛЬ ПРОИЗВОДСТВА. Подсистема прекращает работу, когда прогресс
  // ТЕКУЩЕГО уровня GPL (Game.gpl.progress) достигает этой величины: дальше
  // снабжение PowerSpawn не генерирует задачи и processPower() не вызывается.
  // Без такого условия «включённый PowerSpawn» означал бы бессмысленный вечный
  // цикл «подвезли → обработали → снова подвезли», даже когда уровень уже
  // набран.
  //
  // Порог — не «сумма GPL в комнате», а прогресс уровня: движок копит его в
  // Game.gpl.progress и сбрасывает при переходе на новый уровень
  // (progressTotal текущего уровня — Game.gpl.progressTotal; на shard3
  // 24.09.2026 это 21000 при progress 14788). Поэтому 20000 — «добрать
  // уровень своими силами, но не мешать следующему»: после level-up прогресс
  // падает до нуля, и подсистема включается снова сама.
  //
  // Значение обязано быть ВЫШЕ текущего прогресса, иначе включение флага
  // ничего не даст: подсистема сразу сочтёт цель достигнутой (на shard3 это
  // как раз и произошло бы с порогом 10000).
  TARGET_GPL_PROGRESS: 20000,

  // ПОДВОЗ ЭНЕРГИИ И РЕЗЕРВ КОМНАТЫ.
  //
  // Раньше подвоз требовал `storage > STORAGE.ENERGY_MIN * ENERGY_RESERVE_
  // MULTIPLIER + needed` (более 165 000 при резерве 150 000). Это НЕ резерв, а
  // надбавка 10 %, и в живых RCL8-комнатах shard3 storage держится как раз на
  // 162–167k: порог оказывался недостижим, задача на подвоз не создавалась, и
  // PowerSpawn застывал недозаправленным (453/500 энергии) — processPower()
  // переставал вызываться. Именно так подсистема «умерла» повторно 24.09.2026,
  // уже после включения флага.
  //
  // Сейчас правило то же, что у прочих потребителей (energySource.withdrawFrom
  // Storage): энергию можно брать, пока storage ВЫШЕ резерва, иначе — из
  // терминала. Трата PowerSpawn ограничена механикой (50 энергии раз в 50
  // тиков на комнату ≈ 1/тик), поэтому «вычерпать комнату» он не может:
  //  - ENERGY_STORAGE_FLOOR — минимум, ниже которого энергия берётся только из
  //    терминала (сам резерв остаётся неприкосновенным);
  //  - ENERGY_TERMINAL_FLOOR — сколько энергии должно быть в терминале, чтобы
  //    брать оттуда при пустом по резерву storage (буфер комнаты и комиссии
  //    маркета остаются целы).
  ENERGY_STORAGE_FLOOR: STORAGE.ENERGY_MIN,
  ENERGY_TERMINAL_FLOOR: 20000,
};

module.exports = {
  POWER_SPAWN,
};
