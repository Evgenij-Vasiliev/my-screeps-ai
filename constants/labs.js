// ── LAB BOOST (boost-lab обычной комнаты) ────────────────────────────────
// Буст-лаба НЕ производит реагенты: она получает готовый буст из
// storage/terminal комнаты (доставку обеспечивает существующий terminalNetwork
// — boostLab включён в labWorker.getConfigs, поэтому его ресурсы попадают в
// reagentList/resourceInLabs и защищены от продажи рынком) и используется для
// бустирования местных крипов.
//
// Отдельного планировщика нет: логику ведёт boost.manager из уже существующего
// цикла по крипам комнаты (room.manager.runCreepLogic). Крип, которому нужен
// буст, сам приезжает к буст-лабе и вызывает creep.boost() — так же, как
// labWorker приезжает за реагентом. Действия крипа подавляются ровно на время
// буста, чтобы worker.runner не увёл его в Task посреди процедуры.
//
// ПОЛИТИКА (ТЗ §5, §6, §12): первый буст обычной комнаты — XKH2O (CARRY),
// второй — XZHO2 (MOVE). Боевые бусты (XKHO2/XLHO2) мирным крипам не выдаются
// вообще, а XUHO2 (harvest 7 — добычный WORK-буст) зарезервирован под
// постоянных remote-майнеров и не расходуется на обычных Worker: комнатный крип
// получает XUHO2, только если он удалённая роль контура (см. BOOST_POLICY).
// ВНИМАНИЕ: в прежней редакции здесь стояло имя XUH2O — это ДРУГОЙ ресурс
// (utrium acid, буст ATTACK 4 из реакции UH + OH), для майнера он бесполезен.
// Добычный буст — XUHO2 (utrium alkalide, harvest 7, реакция UO + OH → UHO2 → X).
//
// MIN_STOCK — сколько boost-ресурса должно быть в наличии СУММАРНО по комнате
// (буст-лаба + storage + terminal + реакторы троек), чтобы буст вообще начинался.
// Считает именно СУММУ boost.manager.available, прекращая обход, как только порог
// достигнут: запас, раздробленный по источникам (живой shard3: 125 в терминале и
// 330 в реакторах при пороге 150), — тоже действительный запас; подробности в
// комментарии к available. Это не порог экономики, а
// защита контура: обычный Worker не имеет права съесть буфер, из которого живёт
// SK-группа. Частей бустится не больше parts — тело воркера на 3000 единиц
// буста не тратится.
