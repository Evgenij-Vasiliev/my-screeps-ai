/**
 * Можно ли спавнить роль с сокращённым (бустнутым) телом: в НУЖНОЙ буст-лабе
 * комнаты лежит оплаченный комплект под первый ресурс политики роли.
 *
 * Считает по уже собранному roomState.labs — без room.find и без
 * Game.getObjectById, как и остальные потребители буст-лабы (roomState.labs
 * наполняется сканером один раз за тик).
 *
 * @param {Object} roomState
 * @param {string} role
 * @returns {boolean}
 */
function boostReadyForSpawn(roomState, role) {
  const policy = LAB_BOOST.BOOST_POLICY[role];
  if (!policy || !policy.length) return false;

  const row = policy[0];
  if (!row || !row.resource || !row.parts) return false;

  const configured = LAB_BOOST.BOOST_LAB[roomState.roomName];
  const labId = configured && configured[row.resource];
  if (!labId) return false;

  const labs = roomState.labs;
  if (!labs || !labs.length) return false;

  // Движок тратит LAB_BOOST_MINERAL 30 и LAB_BOOST_ENERGY 20 на КАЖДУЮ часть
  // (engine src/processor/intents/labs/boost-creep.js), поэтому комплект —
  // parts × 30 минерала И parts × 20 энергии в одной и той же лабе.
  const needMineral = row.parts * 30;
  const needEnergy = row.parts * 20;

  for (let i = 0; i < labs.length; i++) {
    const lab = labs[i];
    if (!lab || lab.id !== labId) continue;
    const store = lab.store;
    if (!store) return false;
    return (
      (store[row.resource] || 0) >= needMineral &&
      (store[RESOURCE_ENERGY] || 0) >= needEnergy
    );
  }
  return false;
}

