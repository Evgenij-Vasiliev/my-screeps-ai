/**
 * ТЕЛА ПРИ НАЛИЧИИ БУСТА (правка 02.10.2026). Правило владельца: как только
 * буст есть, тело сокращается пропорционально его множителю, а если буста нет —
 * роль спавнится с ПОЛНЫМ телом (CREEP_BODIES), как раньше.
 *
 * Почему сокращение вообще возможно, посчитано по движку:
 * utils.calcBodyEffectiveness даёт iPower = basePower × BOOSTS[тип][буст][метод],
 * то есть каждая бустнутая часть тела работает КРАТНО сильнее:
 *   - WORK с UO: BOOSTS.work.UO.harvest = 3 → 2 × 3 = 6 за часть;
 *   - CARRY с KH: BOOSTS.carry.KH.capacity = 2 → 50 × 2 = 100 за часть.
 * Значит ту же работу делает втрое меньше WORK-частей и вдвое меньше CARRY.
 *
 * ЧИСЛА (что именно заменяет полное тело):
 *   miner   35 WORK → 12 WORK: 12 × 6 = 72 против прежних 35 × 2 = 70 за удар
 *           (источник ограничен 3000/300 = 10/тик, выше 70 смысла нет);
 *   worker  32 CARRY → 16 CARRY: 16 × 100 = 1600, ровно как 32 × 50;
 *   labWorker 6 CARRY → 3 CARRY: 3 × 100 = 300 = 6 × 50 (комплект 180 KH);
 *   linkWorker 4 CARRY → 2 CARRY: 2 × 100 = 200 = 4 × 50 (комплект 120 KH).
 *
 * ЦЕНА БУСТА НЕ ПАДАЕТ при сокращении тела: платят за бустнутые части, а не за
 * размер. Выигрыш в другом — энергия и время спавна: 12 WORK + 7 CARRY + 8 MOVE
 * это 27 частей против 50 (810 вместо 1500 энергии, 81 вместо 150 тиков спавна),
 * а CARRY с KH несёт вдвое больше при ТОЙ ЖЕ усталости — движок считает вес
 * груза с учётом буста (engine src/processor/intents/movement.js:41-58).
 *
 * ВАЖНО: тело выбирается по НАЛИЧИЮ БУСТА В ЛАБЕ, а не по факту его выдачи.
 * Крип, родившийся с сокращённым телом БЕЗ буста, проработает всю жизнь (1500
 * тиков) втрое слабее — это худший исход, чем лишние части. Поэтому условие
 * строгое: достаточно оплаченного комплекта в буст-лабе ПРЯМО СЕЙЧАС.
 */
