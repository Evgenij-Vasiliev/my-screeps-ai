/**
 * Время спавна тела роли в тиках: движок тратит SPAWN_TICKS_PER_PART тиков на
 * каждую часть тела (в тестовой среде константа движка недоступна, поэтому
 * держим её здесь — она неизменна и одинакова для всех ролей).
 * @param {string} role
 * @returns {number}
 */
function spawnTimeOf(role) {
  const SPAWN_TICKS_PER_PART = 3;
  const blueprint = CREEP_BODIES[role] || {};
  let parts = 0;
  for (const part of Object.keys(blueprint)) parts += blueprint[part];

  return parts * SPAWN_TICKS_PER_PART;
}

/**
 * Самое долгое время хода роли до рабочей цели по всем удалённым комнатам.
 * @param {string} role
 * @returns {number} тиков
 */
function longestRemoteRoute(role) {
  const routes = REMOTE_ROUTE_TICKS[role] || {};
  let longest = 0;

  for (const room of REMOTE.ROOMS) {
    const ticks = routes[room];
    if (typeof ticks === "number" && ticks > longest) longest = ticks;
  }

  return longest;
}

/**
 * Порог пре-спавна удалённой роли: спавн + дорога + запас.
 *
 * Пре-спавн существует ровно для одного: замена должна ПРИБЫТЬ к работе не
 * позже смерти предшественника. Значит окно замены — это время спавна тела
 * плюс время хода до рабочей цели в удалённой комнате плюс небольшой запас.
 * Раньше здесь стояли круглые числа «спавн + 100 на дорогу» для всех трёх
 * ролей сразу, и для remoteMiner (самая длинная дорога — 82 тика) замену
 * ставили за 96 тиков до смерти, то есть замена опаздывала на ~36 тиков.
 * Для reserver наоборот: его дорога 88 тиков при спавне 18 — прежние 120
 * тиков открывали слот на 200+ тиков жизни раньше нужного.
 *
 * @param {string} role
 * @returns {number} тиков
 */
function remotePreSpawnThreshold(role) {
  return (
    spawnTimeOf(role) + longestRemoteRoute(role) + REMOTE.HANDOFF_SAFETY_MARGIN
  );
}

// ── CREEP_BODIES ─────────────────────────────────────────────────────────
// Тело (набор частей) для каждой роли. Порядок частей в самом крипе
