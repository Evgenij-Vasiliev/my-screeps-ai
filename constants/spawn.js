// ── PRESPAWN_THRESHOLD ───────────────────────────────────────────────────
// За сколько тиков до смерти крипа (по ticksToLive) роль считается
// "скоро освободится" и заранее запускается пре-спавн замены.
// Пре-спавн — это замена роли ЗАРАНЕЕ, чтобы она не исчезала из комнаты:
// countRole() перестаёт считать крипа, когда его ticksToLive <= порога
// (spawn.manager.js, isPreSpawnCandidate), поэтому квота открывается ещё до
// смерти старого крипа и замена успевает встать ему на смену.
//
// Порог не может быть меньше времени спавна: движок тратит 3 тика на часть
// тела (SPAWN_CREEP_TIME), поэтому замена, начатая позже, физически не успеет
// появиться до смерти предшественника.
//
// У ДАЛЬНИХ РОЛЕЙ (reserver / remoteMiner / remoteHauler) задача другая, чем
// у домашних: замена должна не просто «встать в комнате», а ПРИЙТИ в удалённую
// комнату, пока предшественник ещё жив или ровно к моменту его смерти. Поэтому
// их порог считается по формуле, а не берётся круглым числом:
//
//   порог = время спавна + время хода до рабочей цели + REMOTE.HANDOFF_SAFETY_MARGIN
//
// Время спавна — из тела роли (3 тика × частей), время хода — замер движком
// по реальному террейну shard3 (REMOTE_ROUTE_TICKS выше). Итог для худшей из
// удалённых комнат (E35S38, дорога 82 тика):
//   reserver:     6 частей → спавн  18 + 88 + 30 = 136
//   remoteMiner: 18 частей → спавн  54 + 82 + 30 = 166
//   remoteHauler: 40 частей → спавн 120 + 82 + 30 = 232
//
// Для remoteMiner это и есть критическое требование «replacement arrival <=
// predecessor death»: спавн 54 + дорога 82 = 136 ≤ 166, то есть замена входит
// в удалённую комнату за ~30 тиков ДО смерти предшественника и источник не
// простаивает.
// Для remoteHauler окно шире жизни на дорогу быть не может: спавн 120 + 82 =
// 202 — это физический минимум, и он не превышает порог 232. Замена начинает
// путь в комнату уходящего сразу после выхода из спавна — то есть не стоит у
// спавна без цели.
// Для reserver помним, что CLAIM-части укорачивают жизнь крипа до 600 тиков
// (а не 1500): окно 136 — это ~23 % его жизни, а резерв (5000 тиков) после
// смерти старого не истекает.
const PRESPAWN_THRESHOLD = {
  // miner: 130. Расчёт под НОВОЕ тело (10 WORK / 6 CARRY / 4 MOVE, см.
  // CREEP_BODIES.miner): спавн 20 частей × 3 = 60 тиков; дорога — худший живой
  // путь до спота 20 клеток (замер findPathTo от спавна до memory.spot) при
  // 16 «тяжёлых» частях и 4 MOVE = 16 / (4 × 2) = 2 тика на клетку → 40 тиков.
  // Итого 100 + запас 30 тиков на очередь спавна и трафик. Прежние 100 были
  // ровно равны «спавн 39 + дорога 55 = 94» у тела из 13 частей; после правки
  // тела та же цифра 100 обратилась бы в ноль запаса (60 + 40 = 100), и замена
  // приходила бы к источнику одновременно со смертью предшественника — то есть
  // любой сбой очереди спавна означал бы простой источника.
  miner: 130,
  remoteMiner: remotePreSpawnThreshold("remoteMiner"),
  reserver: remotePreSpawnThreshold("reserver"),
  remoteHauler: remotePreSpawnThreshold("remoteHauler"),
  // linkWorker: порог по той же формуле, что у дальних ролей, только без
  // удалённой комнаты — «спавн + дорога + запас»:
  //   спавн 5 частей (4 CARRY / 1 MOVE) = 15 тиков;
  //   дорога: спавн → storage-линк — 1–5 клеток (живой замер findPathTo по всем
  //   пяти комнатам), при MOVE 1 на дорогах 2 тика на клетку → до 10 тиков;
  //   запас 13 тиков на трафик и очередь спавна.
  // Итого 38. Прежние 30 оставляли всего 15 тиков на дорогу из 10 расчётных —
  // впритык: задержка спавна означала бы полный линк, а полный линк блокирует
  // добычу майнера (linkManager не может отправить в заполненный приёмник).
  linkWorker: 38,
  // Воркер — единственный, кто доливает спавны/расширения из storage.
  // Тело — 24 части (2 WORK / 10 CARRY / 12 MOVE), спавн 72 тика (3 × 24).
  // Порог оставлен 150 намеренно с бОльшим запасом, чем у прежней формулы
  // «спавн + 30»: пропуск этой роли опаснее лишнего перекрытия, а замена
  // успевает встать заранее.
  worker: 150,
};

