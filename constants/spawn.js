/**
 * Порог минерала для спавна mineralMiner. Было 1500 (правка 02.10.2026).
 *
 * Замер shard3 (node scripts/measure.mineral.js shard3, Game.time 83376031..83376109):
 * во всех пяти своих комнатах (RCL 8) экстрактор есть, но amount =
 * E35S37 K 130, E35S39 H 300, E37S37 L 810, E37S38 U 380, E36S38 L 415 —
 * все ПЯТЬ ниже 1500. Два снимка с интервалом 20 с: amount не менялся,
 * extractor.cooldown = 0 → добыча не шла вовсе, живых mineralMiner 0
 * (Memory.creeps: linkWorker 5, labWorker 5, miner 5, worker 5).
 * Подтверждение с шарда: global.__spawnGate = {E35S37:3, E35S39:1, E36S38:10,
 * E37S37:10, E37S38:9} при SPAWN.SCAN_INTERVAL = 10 — это ветка простоя
 * (spawn.manager.js:245-247), то есть roomWants = false из-за этой строки.
 *
 * Почему 1, а не «половина тела»: ветка «минерал исчерпан» уже закрыта
 * отдельно — при mineralAmount === 0 состояние не строится вовсе
 * (mineral.manager.js:22-25) и шлюз отсекает роль на проверке
 * `!roomState.mineral` (spawn.manager.js:206). Отсюда любой порог > 0 даёт
 * ровно то же поведение «не спавнить впустую», а большое значение вредит:
 * при исчерпании минерала майнер умирает, и следующий спавн ждёт регенерации
 * (MINERAL_REGEN_TIME = 50000 тиков, engine/src/processor/intents/minerals/tick.js)
 * — цикл добычи теряется целиком.
 *
 * Цена ошибки в обе стороны мала: майнер {5 WORK, 5 CARRY, 5 MOVE} стоит 1000
 * энергии (5×100 + 5×50 + 5×50, BODYPART_COST) и 45 тиков спавна (3 тика на
 * часть), 5 CARRY вмещают 250 единиц, то есть даже на
 * минимуме замера (130) майнер уходит с полной поклажей и тело не
 * «выбрасывается». Выход добычи задан не этим порогом, а производительностью:
 * HARVEST_MINERAL_POWER 1 × 5 WORK = 5 единиц за успешный harvest, и он
 * повторяется раз в EXTRACTOR_COOLDOWN = 5 тиков — устоявшийся выход
 * 5/5 = 1 единица/тик на комнату. Подтверждено на живом шарде после выгрузки
 * (node scripts/watch.mineral.js shard3, Game.time 83376227): amount падал
 * ровно на 5 за событие — E35S39 300→280, E37S37 810→795, E36S38 415→405, —
 * а extractor.cooldown при этом 0→5 и 0→4, то есть за 5 тиков кулдауна
 * успевает ровно один harvest. (Прежняя оценка «≈0.83/тик» исходила из цикла
 * 6 тиков и замером не подтвердилась — исправлено.)
 *
 * Откат: MINERAL_MIN_AMOUNT_TO_SPAWN = 1500.
 */
const MINERAL_MIN_AMOUNT_TO_SPAWN = 1;

