// ===================================================
// Резерв энергии Storage, пороги пополнения терминала (TERMINAL_SUPPLY)
// и параметры межкомнатной балансировки через Terminal.send()
// (TERMINAL_NETWORK). Энергополы терминала и склада живут здесь вместе,
// потому что это один предмет: сколько комната обязана держать у себя.
// Выделено из constants.js; потребители берут значения через barrel
// constants.js, чтобы объекты конфига оставались одним экземпляром.
// ===================================================
// ── STORAGE ──────────────────────────────────────────────────────────────
// Резерв энергии в Storage комнаты.
const STORAGE = {
  ENERGY_MIN: 150000, // не опускаться ниже — резерв комнаты
};

// ── TERMINAL_SUPPLY ──────────────────────────────────────────────────────
// Пороги пополнения терминала энергией/ресурсами из Storage.
// Единый источник порогов — market.manager.js продаёт всё, что превышает
// эти же значения, чтобы не было двух разных источников правды.
//
// ДВА РАЗНЫХ ЧИСЛА, КОТОРЫЕ РАНЬШЕ ПУТАЛИСЬ (100000/150000 → 10000/20000).
// ENERGY_MIN — это НЕ «порог, ниже которого терминал подвозят»: появление
// задачи fillTerminalEnergy от него не зависит вовсе (task.generators.js:263
// сравнивает с ENERGY_TARGET). ENERGY_MIN — это ПОЛ ОСТАТКА терминала-донора,
// ниже которого он не отдаёт ресурс по сети (terminalNetwork.fitSendAmount,
// terminalNetwork.js:662) и не считается донором энергии в balanceEnergy
// (terminalNetwork.js:752). Два режима работы терминала требуют разных чисел:
//
//  1. ENERGY_MIN 10000. Прежние 100000 делали терминал НЕДОСТИЖИМЫМ донором:
//     balanceEnergy требовал `terminalEnergy > ENERGY_MIN + MIN_SEND_AMOUNT`
//     (101000), а живая энергия терминалов 6.8–26.5k (замер в docs/
//     SESSION_HANDOFF.md, тот же, по которому PRIORITY_ENERGY_FLOOR и
//     MARKET.BUY_ENERGY_FLOOR уже понижены до 10000). То есть обычная
//     балансировка не отправляла НИЧЕГО, и весь межкомнатный обмен ресурсами
//     шёл только «приоритетным» обходом. 10000 — тот же уровень, что у
//     PRIORITY_ENERGY_FLOOR (constants.js:77) и MARKET.BUY_ENERGY_FLOOR:
//     один энергопол на все три механизма вместо трёх разных.
//     Риск понижения (намеренно принят): терминал имеет право отдать энергию
//     до 10000. Расширения/спавны защищены не этим полом, а STORAGE.ENERGY_MIN
//     (150000) и живым запасом storage — энергия как РЕСУРС отправляется по
//     ветке `energyAfter = energy − amount − cost`, то есть комиссия и объём
//     списываются из одного остатка и проверяются по этому же полу.
//
//  2. ENERGY_TARGET 100000 — ЛИМИТ ВЛАДЕЛЬЦА: «энергия в терминале должна быть
//     всегда, и её всегда и на всё должно хватать». Это НЕ подбор числа, а
//     требование: комиссии платятся энергией ТЕРМИНАЛА-инициатора, и при живой
//     энергии терминалов 8112–9404 отваливались даже продажи battery
//     (market.manager.js:384: «нужно 1321 + резерв 10000, есть 9404»).
//     Арифметика порога: SELL_ENERGY_FLOOR 10000 + комиссия партии 5000 battery
//     (d=3 → 1321, d=4 → 1530, d=15 → 4878) = 11321…14878; отправка 2000 единиц
//     реагента на 15 комнат ≈ 1554; при MAX_DEALS_PER_TICK 6 комиссии одного
//     тика складываются (общего бюджета нет — каждая сделка читает живой store).
//     100000 покрывает это с запасом.
//     Здесь же была настоящая ошибка логики: исполнитель задачи останавливался
//     на `isTargetFull(target)` (task.executors.js:398), то есть ЛИЛ ТЕРМИНАЛ ДО
//     ПОЛНОЙ ЁМКОСТИ 300k, тогда как генератор считал потребностью разницу до
//     ENERGY_TARGET (task.generators.js:263). Теперь обе стороны согласованы:
//     исполнитель тоже останавливается на ENERGY_TARGET.
//
// ГЕЙТ ПОДВОЗА — 1.3 × РЕЗЕРВ СКЛАДА (195000). ЭТО ПРАВИЛО ВЛАДЕЛЬЦА.
// Склад отдаёт энергию терминалу ТОЛЬКО из излишка выше
// STORAGE.ENERGY_MIN × STORAGE_RESERVE_MULTIPLIER = 195000, то есть после
// резерва комнаты (150000) и 45k буфера фабрики (FACTORY 1.1 × 150000 = 165000).
// Генератор (task.generators.js) и исполнитель (task.executors.js) проверяют
// один и тот же порог, поэтому склад ниже ~195k не опускается. Понижать гейт
// НЕЛЬЗЯ — он и есть защита склада.
//
// Следствие, которое надо держать в голове (именно оно даёт «в терминале никогда
// нет энергии»): пока склад ниже 195000, у терминала нет НИ ОДНОГО притока —
// линки льют в storage (linkManager.js), MARKET.BUY_RESOURCES энергию не
// содержит, terminalNetwork.balanceEnergy требует донора со складом > 195000, —
// а стоки работают: комиссии send/рынка и аварийный вывод воркерами через
// energySource.js:47 при storage ≤ 150000. Поэтому «в терминале всегда есть
// энергия» достигается не понижением порога, а тем, что склад выходит выше
// 195000: либо растёт доход, либо сокращаются стоки комнаты.
//
// Если менять любое из чисел — менять осознанно: ENERGY_MIN завязан на
// PRIORITY_ENERGY_FLOOR/BUY_ENERGY_FLOOR (единый энергопол), ENERGY_TARGET — на
// isTargetFull-ветку исполнителя и на порог комиссий рынка (SELL_ENERGY_FLOOR +
// комиссия сделки), STORAGE_RESERVE_MULTIPLIER — на гейт подвоза терминала и на
// выбор донора в terminalNetwork.balanceEnergy.
const TERMINAL_SUPPLY = {
  ENERGY_MIN: 10000, // пол остатка терминала-донора (не порог подвоза!)
  ENERGY_TARGET: 100000, // цель подвоза: терминал держит столько энергии всегда (лимит владельца) И точка остановки исполнителя
  MINERAL_MAX: 0, // терминал не должен копить минералы сверх этого
  BATTERY_MAX: 0, // терминал не должен копить battery сверх этого
  COMPOUND_MAX: 0, // терминал не должен копить compounds сверх этого
  STORAGE_RESERVE_MULTIPLIER: 1.3, // множитель к STORAGE.ENERGY_MIN: склад отдаёт энергию терминалу и считается донором только выше этого уровня (195000)
};

// ── TERMINAL_NETWORK ─────────────────────────────────────────────────────
// Межкомнатная балансировка через Terminal.send().
// Энергию считаем по Storage (им живёт экономика), прочие ресурсы —
// по сумме Storage + Terminal (добыть можно только то, что уже в терминале).
const TERMINAL_NETWORK = {
  MIN_SEND_AMOUNT: 1000, // меньше не шлём — комиссия не окупается
  RESOURCE_SURPLUS_ABOVE: 10000, // суммарный запас ресурса выше этого — донор
  RESOURCE_DEFICIT_BELOW: 2000, // суммарный запас ниже этого — получатель
  RESOURCE_TARGET: 5000, // до какого суммарного уровня докидываем получателю
  LAB_REQUEST_BELOW: 3000, // ниже этого локального запаса реагента комната запрашивает сеть
  // Донор, у которого та же реакция, столько оставляет себе. Понижено с 3000 по
  // живому замеру: availableToGive = (терминал + склад + ЛАБОРАТОРИИ) − keep, а у
  // единственного производителя KH2O (E35S39) запас ровно 3000 (150 в терминале
  // + 2850 в реагентной лабе своей же тройки) — при keep 3000 излишек был РОВНО
  // нулевым, findDonor отбрасывал донора (нужно ≥ MIN_SEND_AMOUNT = 1000), и
  // четыре комнаты стояли с пустыми реагентными лабами при полном складе у
  // производителя. 1000 = одна минимальная поставка: донор отдаёт то, что ВЫШЕ
  // неё, а фактический объём всё равно ограничен терминалом (fitSendAmount:
  // amount = min(desired, terminal.store[ресурс])), поэтому своя лаба не
  // оголяется — из неё отправка не идёт вовсе.
  LAB_KEEP: 1000,
  LAB_SHIP_AMOUNT: 3000, // объём одной поставки реагента

  // ── СКОЛЬКО ЛАБ-ПОСТАВОК ДЕЛАТЬ ЗА ТИК (ТЗ владельца «ЗАПУСТИТЬ ЛАБЫ — ВСЕ»)
  // ─────────────────────────────────────────────────────────────────────────
  // Раньше run() выходил по ПЕРВОЙ успешной отправке, то есть на всю империю
  // приходилась ОДНА поставка за тик, какого бы ресурса она ни касалась. Живой
  // замер 25.09.2026 (tick 83194506): 11 из 15 троек на паузе, и у большинства
  // недостающий реагент — сырьё, которое в империи ЕСТЬ, но в другой комнате
  // (E37S37 требует O и H, которых в её терминале нет, при O 4105 в E36S38;
  // E35S37 требует X при X 1800 в E35S39). Один рейс в тик на пять комнат — это
  // и был весь подвоз.
  //
  // Значение 3, а не «без лимита»: каждая поставка списывает комиссию с энергии
  // терминала-донора, а PRIORITY_ENERGY_FLOOR (10000) проверяется на КАЖДУЮ
  // отправку. Три — верхняя граница, при которой донор остаётся выше пола.
  LAB_SENDS_PER_TICK: 3,
  STATUS_INTERVAL: 50, // раз в сколько тиков писать статус, если send не было

  // ── Пол энергии для ПРИОРИТЕТНОЙ поставки реагентов финального производства
  // (LAB_PRIORITY) ─────────────────────────────────────────────────────────
  // Обычный порог энергии терминала-донора — TERMINAL_SUPPLY.ENERGY_MIN
  // (100 000, см. fitSendAmount). На shard3 он структурно НЕДОСТИЖИМ: задачи
  // fillTerminalEnergy пополняют терминал, только когда энергия Storage выше
  // STORAGE.ENERGY_MIN × STORAGE_RESERVE_MULTIPLIER (195 000), а Storage
  // стабильно держится у своего резерва (замер 25.09.2026: 164–165k во всех
  // пяти комнатах). Энергия терминалов стоит на 50–79k, обычный порог для
  // send недостижим, и ресурс не уезжает вообще НИКОГДА — включая реагенты
  // финальных троек, из-за простоя которых не варятся X-бусты.
  //
  // Поэтому приоритетная поставка реагента финальной реакции (priority > 0 в
  // terminalNetwork) может опустить энергию терминала-донора до этого уровня.
  // Это НЕ отмена резерва: обычные отправки (балансировка ресурсов и энергии)
  // по-прежнему требуют TERMINAL_SUPPLY.ENERGY_MIN, а комиссия приоритетной
  // отправки по-прежнему списывается и проверяется в fitSendAmount.
  //
  // ЗНАЧЕНИЕ ПЕРЕСМОТРЕНО ПО ЖИВОМУ ЗАМЕРУ. 20000 калибровались под энергию
  // терминалов 50–79k (замер 25.09.2026), но фактически она держится на
  // 6.8–26.5k (живой замер: E35S39 18915, E36S38 11258, E37S37 13038,
  // E35S37 6831 при E37S38 26517). При пороге 20000 отправлять могла только
  // одна комната из пяти: KH2O с 1300 в терминале и 2855 в лабе E35S39
  // (излишек 1155 при LAB_KEEP 3000) не уезжал в E35S37, и XKH2O-тройки стояли.
  // 10000 — половина прежнего порога, при этом на порядок больше комиссии
  // отправки (1554 энергии за 2000 XKH2O) и достаточно для подпитки спавнов.
  PRIORITY_ENERGY_FLOOR: 10000,
};

