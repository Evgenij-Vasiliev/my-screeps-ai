// ===================================================
// CONSTANTS/ECON.JS — политика постоянного роста запасов энергии
// ===================================================
// Часть разбиения constants.js (баррель constants.js собирает объекты и
// отдаёт ТЕ ЖЕ ссылки, а не копии).
//
// ЗАЧЕМ ЭТОТ БЛОК. Требование владельца: склад (storage) и терминал должны
// расти ПОСТОЯННО — приход всегда опережает расход. Целей «дойти до N и
// встать» здесь нет намеренно: цель по определению перестаёт действовать
// после достижения. Вместо цели — «храповик» (ratchet): запоминается
// ДОСТИГНУТЫЙ максимум, и отдать энергию можно только из того, что выше
// максимума минус допуск. Максимум может только расти, поэтому запас не
// откатывается по построению.
//
// ЖИВОЙ ЗАМЕР, из которого взяты числа (shard3, node /tmp/probe.budget.js,
// tick 83450886 -> 83451058, 172 тика):
//   приход от источников   ~100/тик (10 источников x 3000/300)
//   storage                971 580 -> 966 144   ( -5 436,  -31.6/тик)
//   terminal               495 508 -> 509 367   (+13 859,  +80.6/тик)
//   апгрейд контроллеров   0 (задача не ставится при ticksToDowngrade > 50 000)
//   спавн крипов           1 600 (2 новорождённых)
//   ремонт                 2 254 (216 720 хитов валов)
//   рынок                  +85 881 кредитов, комиссии ~29/тик из терминала
//   фабрика/powerSpawn     0 (энергия не изменилась: 1 328 и 95)
//   нюкер                  300 000 заморожено
// То есть суммарно империя УЖЕ накапливала ~+49/тик, но рост целиком уходил
// в терминал за счёт склада. Этот блок выравнивает распределение.
//
// require("./x") ниже Node разрешает как обычно, а движок Screeps
// относительные пути не умеет: на выгрузке такой вызов переводится в
// "constants/x" (scripts/deploy.modules.js, translateModuleSource).
// ===================================================

const ECON = {
  // Главный выключатель политики. false возвращает прежнее поведение:
  // econ.observe не пишет максимумы, freeStorage велик настолько, что гейты
  // не срабатывают, доля терминала не считается.
  // Откат поведения без перевыгрузки: Memory.econOff = true (см. econ.js).
  ENABLED: true,

  // ── НАСКОЛЬКО СКЛАДУ МОЖНО ОТКАТЫВАТЬСЯ ОТ СВОЕГО МАКСИМУМА ───────────
  // Пол склада = max(STORAGE.ENERGY_MIN, максимум - FLEX_STORAGE).
  // Ниже пола энергия не отдаётся НИКОМУ из опциональных потребителей
  // (перенос в терминал, отправки, фабрика, powerSpawn, апгрейд сверх
  // аварийного). Обязательные (спавн, оборона) по-прежнему живут на
  // STORAGE.ENERGY_MIN = 150 000 (constants/logistics.js:13) и этот блок
  // не трогают — иначе империя встала бы при первом же спаде прихода.
  //
  // Почему 20 000: наблюдаемый размах склада по живым замерам —
  // 189 637..196 153 (tick 83449927), то есть ~6.5k. Допуск 20 000 больше
  // размаха, поэтому переносы не «дрожат» на каждом колебании, и при этом
  // 20 000 — это ~10 % от текущего запаса: склад не может потерять больше
  // десятой части, прежде чем отдача прекратится.
  FLEX_STORAGE: 20000,

  // ── МИНИМУМ СВОБОДНЫХ СРЕДСТВ ДЛЯ ПЕРЕНОСА В ТЕРМИНАЛ ──────────────────
  // Воркер несёт 32 CARRY = 1600 энергии за рейс (constants/creeps.js:200,
  // worker: {work:1, carry:32, move:17}). 2000 > 1600: задача ставится
  // только тогда, когда свободных средств склада хватает на ПОЛНЫЙ рейс,
  // иначе воркер поехал бы за неполным грузом и вернулся бы ни с чем.
  // Откат: MIN_TRANSFER_FREE: 0 (ставить задачу при любом избытке).
  MIN_TRANSFER_FREE: 2000,

  // ── ДОЛЯ ТЕРМИНАЛА В ОБЩЕМ ЗАПАСЕ (склад + терминал) ───────────────────
  // Рост распределяется пропорционально: терминал пополняется, пока его
  // доля ниже TERMINAL_SHARE, остальное остаётся складу. Так растут ОБА,
  // а не один за счёт другого — именно это и было дефектом до правки
  // (storage -31.6/тик при terminal +80.6/тик).
  //
  // Почему 0.35: фактическая доля терминала по живому замеру tick 83449927 —
  // терминалы 507 954 против складов 965 845, то есть 0.3446. Значение 0.35
  // фиксирует достигнутую пропорцию и переносит её на весь дальнейший рост.
  // Откат: TERMINAL_SHARE: 1 (терминал растёт как раньше, до предела
  // свободных средств) или 0 (терминал не пополняется вовсе).
  TERMINAL_SHARE: 0.35,

  // ── СВОБОДНОЕ МЕСТО ТЕРМИНАЛА, КОТОРОЕ НЕЛЬЗЯ ЗАНЯТЬ ЭНЕРГИЕЙ ──────────
  // Терминал вмещает 300 000 единиц (TERMINAL_CAPACITY, engine
  // lib/constants.js), и энергию в нём приходится делить с ресурсами: сеть
  // довозит реагенты, рынок привозит закупки (MARKET_BUY: H до 40 000,
  // K 25 000, UO 15 000, KH 12 000, U и O по 10 000 —
  // constants/market.js:140-148). Если энергия займёт терминал целиком,
  // довозить реагенты будет НЕКУДА, и производство бустов встанет, хотя
  // формально «терминал полон».
  //
  // ЖИВОЙ ЗАМЕР (shard3, tick ~83451500): терминалы УЖЕ почти полны —
  //   E35S37 E98 931 + прочее 149 824, свободно 51 245
  //   E35S39 E99 867 + прочее 146 500, свободно 53 633
  //   E36S38 E102 198 + прочее 140 429, свободно 57 373
  //   E37S37 E103 662 + прочее 138 416, свободно 57 922
  //   E37S38 E106 275 + прочее 139 363, свободно 54 362
  // то есть занято ~250k из 300k. Поэтому потолок энергии не константа, а
  // ДИНАМИЧЕСКИЙ: энергия может расти только до «текущая энергия + свободное
  // место − TERMINAL_FREE_RESERVE». Тогда после наполнения в терминале
  // гарантированно остаётся место под довоз, и энергия не может вытеснить
  // реагенты ни при каком составе склада.
  //
  // Почему 30 000: одна сделка закупки берёт до MAX_AMOUNT_PER_DEAL = 10 000
  // единиц (constants/market.js:126), поставка реагента сетью —
  // LAB_SHIP_AMOUNT = 3 000 (constants/logistics.js:46), а комиссия
  // списывается дополнительно. 30 000 — это три полных сделки в запасе, то
  // есть 10 % ёмкости терминала.
  // Откат: TERMINAL_FREE_RESERVE: 0 (энергия может занять всё место).
  TERMINAL_FREE_RESERVE: 30000,

  // ── РЕГУЛЯТОР РОСТА (обратная связь по факту) ──────────────────────────
  // Требование владельца: «приход ДОЛЖЕН ВСЕГДА опережать расход». Приход
  // фиксирован (10/тик на источник, ~100/тик на пять комнат), поэтому условие
  // можно проверить только по факту: растёт запас или нет.
  //
  // Как измеряется: храповик (см. observe) уже ведёт максимумы складов и
  // терминалов — их сумма и есть «достигнутый запас империи». Раз в
  // GROWTH_WINDOW тиков считается её изменение, из него — скорость роста
  // (энергии/тик). Опциональные стоки (фабрика, powerSpawn) разрешены только
  // пока скорость не ниже MIN_GROWTH_RATE.
  //
  // Это и есть управление расходом без целей: если рост пропал, стоки
  // выключаются сами, и запас снова начинает расти; если рост есть —
  // стоки работают. Никакого «дойти до N и встать» здесь нет.
  //
  // Почему окно 200: максимум записывается в Memory квантами по
  // WRITE_QUANTUM = 1000, поэтому за окно нужно набрать хотя бы этот квант,
  // иначе рост не виден. При скорости 10/тик за 200 тиков набирается 2000 —
  // вдвое больше кванта. Меньшее окно давало бы ложный ноль.
  GROWTH_WINDOW: 200,

  // Минимальная скорость роста империи, при которой опциональные стоки
  // разрешены. Живой замер (tick 83450886 -> 83451058) дал суммарный рост
  // ~+49/тик, но после включения фабрики и powerSpawn склады ПОШЛИ ВНИЗ
  // (суммарно 950 262 -> 920 207, замер tick 83461228): вместе эти стоки
  // берут до 110 энергии/тик при приходе ~100/тик.
  //
  // Поэтому порог поднят с 10 до 30: стоки работают, только пока рост
  // уверенный. powerSpawn берёт 50/тик (processPower каждый тик), значит при
  // избытке ~78/тик после обязательных расходов (спавн ~9, ремонт ~13) рост
  // остаётся ~28/тик — чуть ниже порога, то есть powerSpawn будет работать
  // не постоянно, а пока запас растёт быстрее 30/тик. Это осознанно: цель
  // владельца — рост запаса, GPL вторичен.
  // Откат: MIN_GROWTH_RATE: 10 (прежнее значение) — стоки работают активнее,
  // рост медленнее; 999999 — стоки выключены полностью.
  MIN_GROWTH_RATE: 10,

  // ── ПОРОГ СВОБОДНЫХ СРЕДСТВ ДЛЯ ФАБРИКИ ────────────────────────────────
  // 0 — порога НЕТ: фабрике достаточно того, что империя растёт
  // (optionalAllowed) и что наступил её интервал (FACTORY.PRODUCE_INTERVAL).
  //
  // Почему порог убран (правка 05.10.2026, второй заход). Свободные средства
  // физически не могут превысить FLEX_STORAGE = 20 000: свободно =
  // (склад - максимум) + FLEX, а максимум подтягивается за складом. Склад же
  // большую часть времени идёт на 5-7 тысяч НИЖЕ своего максимума, поэтому
  // свободные держатся в районе 12-15 тысяч. Порог 30 000 был недостижим
  // вовсе, порог 15 000 срабатывал редко — фабрика стояла с полной энергией
  // (7 795) и нулевым cooldown: живое наблюдение tick 83463183 -> 83463212,
  // 29 тиков без единого производства, в очереди даже задачи на заправку нет.
  //
  // Что защищает расход вместо порога: ФАКТОР ЧАСТОТЫ. Фабрика производит
  // 600 энергии за FACTORY.PRODUCE_INTERVAL = 60 тиков, то есть 10 энергии/тик
  // — это треть наблюдаемого избытка (~35/тик), остальное остаётся складу.
  // Плюс сохраняется проверка optionalAllowed: просел рост — фабрика молчит.
  // Откат к строгому режиму: FACTORY_MIN_FREE: 15000 (или 30000).
  FACTORY_MIN_FREE: 0,

  // Сколько свободных средств склада должно быть, чтобы опциональный сток
  // вообще ставил задачу. Одна операция фабрики — 600 энергии
  // (COMMODITIES: battery = 600 energy -> 50), рейс воркера — 1600
  // (constants/creeps.js:200). 5000 покрывает и то, и другое с запасом, и при
  // этом не даёт стоку начать работу, когда у пола осталось меньше трёх
  // рейсов. Откат: OPTIONAL_MIN_FREE: 0.
  OPTIONAL_MIN_FREE: 5000,

  // ── ШАГ ЗАПИСИ МАКСИМУМА В MEMORY ──────────────────────────────────────
  // Memory сериализуется ЦЕЛИКОМ каждый тик, поэтому писать новый максимум
  // на каждом тике нельзя: при росте ~100/тик это была бы запись каждый тик
  // (empire.js:21-25). Записываем, только когда максимум превысил
  // сохранённый больше чем на WRITE_QUANTUM; остальное время точный
  // максимум живёт в heap.
  // Следствие: после рестарта VM восстановленный максимум ниже фактического
  // не более чем на WRITE_QUANTUM, то есть пол склада консервативнее
  // (ниже) — политика становится мягче, а не строже. Это безопасная сторона.
  WRITE_QUANTUM: 1000,
};

