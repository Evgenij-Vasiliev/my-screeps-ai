// ── LAB_PRIORITY ─────────────────────────────────────────────────────────
// Приоритетная доставка промежуточных компонентов финального производства.
// terminalNetwork делает максимум ОДНУ успешную отправку за тик (return из
// run() после OK), поэтому очередь заявок решает, кто её получит. Обычная
// сортировка «у кого меньше запас» отдаёт отправку любому голодному
// потребителю — в том числе базовому минералу, излишек которого лежит без
// дела; при этом комната финальных X-бустов стоит без реагента и не может
// варить конечный продукт.
